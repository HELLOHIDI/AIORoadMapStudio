export function inferBusinessSubcategories({ category, title, details, mainPackage = false }) {
  if (category !== "business") return [];
  const titleText = String(title ?? "");
  const allText = `${titleText}\n${String(details ?? "")}`;
  return BUSINESS_SUBCATEGORY_OPTIONS.filter((tag) => {
    if (tag === "메인패키지") return mainPackage === true;
    if (tag === "경진대회") return BUSINESS_COMPETITION_TERMS.some((term) => titleText.includes(term));
    if (tag === "수출") return allText.includes("수출") || FOREIGN_COUNTRY_NAMES.some((country) => allText.includes(country));
    return allText.includes(tag);
  });
}
